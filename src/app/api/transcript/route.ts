import { NextRequest, NextResponse } from "next/server";
import { verifyOrigin } from "@/lib/verifyOrigin";
import { enforceRateLimit, getRequestIp } from "@/lib/rate-limit";
import { extractVideoId, parseDuration } from "@/lib/utils";
import {
  VIDEO_METADATA_REVALIDATE_SECONDS,
  fetchVideoMetadataWithFallback,
  fetchYouTubeApiWithRotation,
  getConfiguredYouTubeApiKeys,
} from "@/lib/youtubeApiClient";
import {
  extractDescriptionChapters,
  fetchPublicYouTubeCaptions,
  formatTimestamp,
  type TranscriptLineItem,
} from "@/lib/youtubeCaptions";

export type { TranscriptLineItem };

async function handleTranscriptRequest(
  rawVideoIdOrUrl: string,
  req: NextRequest,
  preferredLang?: string,
) {
  const videoId = extractVideoId(rawVideoIdOrUrl);
  if (!videoId) {
    return NextResponse.json(
      { success: false, error: "Invalid YouTube URL or 11-character video ID." },
      { status: 400 },
    );
  }

  const ip = getRequestIp(req.headers);
  const rl = enforceRateLimit(`transcript:${ip}`, 30, 60 * 60 * 1000);
  if (!rl.allowed) {
    return NextResponse.json(
      { success: false, error: "Too many requests. Please try again later." },
      { status: 429, headers: { "Retry-After": String(rl.retryAfterSeconds) } },
    );
  }

  // 1. Fetch authentic video metadata + live public captions in parallel
  const [captionsResult, apiMetaResult] = await Promise.all([
    fetchPublicYouTubeCaptions(videoId, preferredLang),
    getConfiguredYouTubeApiKeys().length > 0
      ? fetchYouTubeApiWithRotation<{
          items?: Array<{
            snippet?: {
              title?: string;
              channelTitle?: string;
              description?: string;
              tags?: string[];
            };
            contentDetails?: {
              duration?: string;
            };
          }>;
        }>(`videos?part=snippet,contentDetails&id=${encodeURIComponent(videoId)}`, {
          revalidate: VIDEO_METADATA_REVALIDATE_SECONDS,
        })
      : Promise.resolve(null),
  ]);

  let title = captionsResult?.videoDetails?.title || `YouTube Video (${videoId})`;
  let channelTitle = captionsResult?.videoDetails?.author || "YouTube Creator";
  let durationSeconds = captionsResult?.videoDetails?.lengthSeconds || 0;
  let description = captionsResult?.videoDetails?.shortDescription || "";

  if (apiMetaResult?.ok && apiMetaResult.data.items && apiMetaResult.data.items.length > 0) {
    const item = apiMetaResult.data.items[0];
    if (item.snippet?.title) title = item.snippet.title;
    if (item.snippet?.channelTitle) channelTitle = item.snippet.channelTitle;
    if (item.snippet?.description) description = item.snippet.description;
    const durSec = parseDuration(item.contentDetails?.duration || "");
    if (durSec > 0) durationSeconds = durSec;
  }

  if (!description && title === `YouTube Video (${videoId})`) {
    const fallbackMeta = await fetchVideoMetadataWithFallback(videoId);
    if (fallbackMeta) {
      if (fallbackMeta.title) title = fallbackMeta.title;
      if (fallbackMeta.channelTitle) channelTitle = fallbackMeta.channelTitle;
      if (fallbackMeta.description) description = fallbackMeta.description;
    }
  }

  // 2. Return verified YouTube caption lines when available
  if (captionsResult && captionsResult.lines.length > 0) {
    const lastSec = captionsResult.lines[captionsResult.lines.length - 1]?.seconds || 0;
    const finalDurSec = durationSeconds > 0 ? durationSeconds : lastSec;
    const durationFormatted = finalDurSec > 0 ? formatTimestamp(finalDurSec) : "N/A";

    return NextResponse.json(
      {
        success: true,
        hasCaptions: true,
        videoId,
        title,
        channel: channelTitle,
        duration: durationFormatted,
        durationSeconds: finalDurSec,
        source: "youtube-captions",
        languageCode: captionsResult.languageCode,
        languageName: captionsResult.languageName,
        isAutoGenerated: captionsResult.isAutoGenerated,
        availableLanguages: captionsResult.availableLanguages,
        lines: captionsResult.lines,
      },
      {
        headers: {
          "Cache-Control": "public, s-maxage=3600, stale-while-revalidate=86400",
        },
      },
    );
  }

  // 3. Honest fallback: genuine creator-authored description chapters (never fabricated captions)
  const durationFormatted = durationSeconds > 0 ? formatTimestamp(durationSeconds) : "N/A";
  const chapterLines = extractDescriptionChapters(description);
  if (chapterLines.length >= 3) {
    return NextResponse.json({
      success: true,
      hasCaptions: false,
      videoId,
      title,
      channel: channelTitle,
      duration: durationFormatted,
      durationSeconds,
      source: "description-chapters",
      notice:
        "This video does not expose public captions or auto-generated subtitles. Showing the creator's official timestamped chapters from the video description instead.",
      lines: chapterLines,
    });
  }

  // 4. Honest error when neither public captions nor timestamped chapters exist
  return NextResponse.json(
    {
      success: false,
      hasCaptions: false,
      videoId,
      title,
      channel: channelTitle,
      duration: durationFormatted,
      durationSeconds,
      error:
        "No public captions or auto-generated subtitles are available for this video. Try a video with closed captions (CC) enabled, or paste your transcript manually.",
    },
    { status: 404 },
  );
}

export async function GET(req: NextRequest) {
  const originCheck = verifyOrigin(req);
  if (!originCheck.allowed) return originCheck.response;

  const { searchParams } = new URL(req.url);
  const raw =
    searchParams.get("videoId") ||
    searchParams.get("url") ||
    searchParams.get("v") ||
    "";
  const lang = searchParams.get("lang") || undefined;

  if (!raw.trim()) {
    return NextResponse.json(
      { success: false, error: "Provide a YouTube URL or videoId query parameter." },
      { status: 400 },
    );
  }

  return handleTranscriptRequest(raw.trim(), req, lang);
}

export async function POST(req: NextRequest) {
  const originCheck = verifyOrigin(req);
  if (!originCheck.allowed) return originCheck.response;

  const body = await req.json().catch(() => null);
  if (!body || typeof body !== "object") {
    return NextResponse.json(
      { success: false, error: "Invalid JSON body." },
      { status: 400 },
    );
  }

  const obj = body as Record<string, unknown>;
  const raw =
    (typeof obj.videoId === "string" && obj.videoId) ||
    (typeof obj.url === "string" && obj.url) ||
    (typeof obj.videoUrl === "string" && obj.videoUrl) ||
    "";
  const lang = typeof obj.lang === "string" ? obj.lang : undefined;

  if (!raw.trim()) {
    return NextResponse.json(
      { success: false, error: "Please provide a valid YouTube URL or 11-character video ID." },
      { status: 400 },
    );
  }

  return handleTranscriptRequest(raw.trim(), req, lang);
}
