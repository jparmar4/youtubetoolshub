export interface StateTaxScenarioResult {
  netProfit: number;
  federalSelfEmploymentTax: number;
  estimatedFederalIncomeTax: number;
  estimatedStateIncomeTax: number;
  totalSolePropTax: number;
  estimatedSCorpNetSavings: number;
}

/**
 * Computes 2026 Sole Prop vs. S-Corp tax estimates for any state & net profit
 */
export function calculateCreatorStateTaxSummary(
  state: UsStateCreatorTax,
  netProfit: number
): StateTaxScenarioResult {
  const {
    selfEmploymentRate,
    seNetEarningsMultiplier,
    socialSecurityWageBase,
    socialSecurityRate,
    medicareRate,
    additionalMedicareThresholdSingle,
    additionalMedicareRate,
    standardDeductionSingle,
    qbiDeductionRate,
  } = IRS_2026_CONSTANTS;

  const seTaxable = netProfit * seNetEarningsMultiplier;
  const ssTax = Math.min(seTaxable, socialSecurityWageBase) * socialSecurityRate;
  const medicareTax = seTaxable * medicareRate;
  const addMedicare =
    seTaxable > additionalMedicareThresholdSingle
      ? (seTaxable - additionalMedicareThresholdSingle) * additionalMedicareRate
      : 0;
  const federalSelfEmploymentTax = Math.round(ssTax + medicareTax + addMedicare);

  const halfSeDeduction = federalSelfEmploymentTax * 0.5;
  const agi = Math.max(0, netProfit - halfSeDeduction);
  const qbiDeduction = Math.max(0, (netProfit - halfSeDeduction) * qbiDeductionRate);
  const federalTaxableIncome = Math.max(0, agi - standardDeductionSingle - qbiDeduction);

  // Simplified 2026 single progressive federal bracket approximation
  let estFedIncome = 0;
  if (federalTaxableIncome <= 12400) {
    estFedIncome = federalTaxableIncome * 0.1;
  } else if (federalTaxableIncome <= 50400) {
    estFedIncome = 1240 + (federalTaxableIncome - 12400) * 0.12;
  } else if (federalTaxableIncome <= 105700) {
    estFedIncome = 5800 + (federalTaxableIncome - 50400) * 0.22;
  } else if (federalTaxableIncome <= 201775) {
    estFedIncome = 17966 + (federalTaxableIncome - 105700) * 0.24;
  } else {
    estFedIncome = 41024 + (federalTaxableIncome - 201775) * 0.32;
  }

  const estimatedFederalIncomeTax = Math.round(estFedIncome);
  const estimatedStateIncomeTax = Math.round(
    netProfit * (state.effectiveRateAt100k / 100)
  );
  const totalSolePropTax =
    federalSelfEmploymentTax + estimatedFederalIncomeTax + estimatedStateIncomeTax;

  // S-Corp model: 45% reasonable W-2 salary above $60K profit, minus ~$2,200 payroll/filing overhead
  let estimatedSCorpNetSavings = 0;
  if (netProfit >= 60000) {
    const reasonableSalary = Math.min(netProfit * 0.45, socialSecurityWageBase);
    const sCorpFica = reasonableSalary * selfEmploymentRate;
    const grossFicaSaved = Math.max(0, federalSelfEmploymentTax - sCorpFica);
    const extraStateEntityTax =
      state.stateCode === "CA"
        ? Math.max(800, netProfit * 0.015)
        : state.stateCode === "IL"
        ? netProfit * 0.015
        : state.llcAnnualFee;
    estimatedSCorpNetSavings = Math.max(
      0,
      Math.round(grossFicaSaved - 2200 - extraStateEntityTax)
    );
  }

  return {
    netProfit,
    federalSelfEmploymentTax,
    estimatedFederalIncomeTax,
    estimatedStateIncomeTax,
    totalSolePropTax,
    estimatedSCorpNetSavings,
  };
}

